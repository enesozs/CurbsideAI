// Generates public/THIRD_PARTY_NOTICES.txt: licence texts of every production dependency bundled
// into the site, plus the fonts, map data and map style served with it. Runs before each build
// (npm "prebuild"), so the notices always match what is shipped.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "public", "THIRD_PARTY_NOTICES.txt");

const paths = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], { cwd: root, encoding: "utf8" })
  .split("\n")
  .filter((p) => p && p !== root.replace(/\/$/, ""));

// Standard SPDX texts, used only when a package ships no licence file (holder from its "author" field).
const TEMPLATES = {
  MIT: (h) => `MIT License\n\nCopyright (c) ${h}\n\nPermission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files (the "Software"), to deal in the Software without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to do so, subject to the following conditions:\n\nThe above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software.\n\nTHE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.`,
  "BSD-3-Clause": (h) => `BSD 3-Clause License\n\nCopyright (c) ${h}\n\nRedistribution and use in source and binary forms, with or without modification, are permitted provided that the following conditions are met:\n\n1. Redistributions of source code must retain the above copyright notice, this list of conditions and the following disclaimer.\n\n2. Redistributions in binary form must reproduce the above copyright notice, this list of conditions and the following disclaimer in the documentation and/or other materials provided with the distribution.\n\n3. Neither the name of the copyright holder nor the names of its contributors may be used to endorse or promote products derived from this software without specific prior written permission.\n\nTHIS SOFTWARE IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS "AS IS" AND ANY EXPRESS OR IMPLIED WARRANTIES, INCLUDING, BUT NOT LIMITED TO, THE IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS FOR A PARTICULAR PURPOSE ARE DISCLAIMED. IN NO EVENT SHALL THE COPYRIGHT HOLDER OR CONTRIBUTORS BE LIABLE FOR ANY DIRECT, INDIRECT, INCIDENTAL, SPECIAL, EXEMPLARY, OR CONSEQUENTIAL DAMAGES (INCLUDING, BUT NOT LIMITED TO, PROCUREMENT OF SUBSTITUTE GOODS OR SERVICES; LOSS OF USE, DATA, OR PROFITS; OR BUSINESS INTERRUPTION) HOWEVER CAUSED AND ON ANY THEORY OF LIABILITY, WHETHER IN CONTRACT, STRICT LIABILITY, OR TORT (INCLUDING NEGLIGENCE OR OTHERWISE) ARISING IN ANY WAY OUT OF THE USE OF THIS SOFTWARE, EVEN IF ADVISED OF THE POSSIBILITY OF SUCH DAMAGE.`,
};

const seen = new Map();
for (const p of paths) {
  const pkgFile = join(p, "package.json");
  if (!existsSync(pkgFile)) continue;
  const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
  const id = `${pkg.name}@${pkg.version}`;
  if (seen.has(id)) continue;
  const licFile = readdirSync(p).find((f) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(f));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "UNKNOWN";
  const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
  let text = licFile ? readFileSync(join(p, licFile), "utf8").trim() : null;
  if (!text && TEMPLATES[license] && author) {
    text = `(No licence file in the package; standard ${license} text with the holder from its author field.)\n\n${TEMPLATES[license](author)}`;
  }
  seen.set(id, { id, license, text });
}

const inter = readFileSync(join(root, "node_modules/@fontsource-variable/inter/LICENSE"), "utf8");
const oflBody = inter.slice(inter.indexOf("-----------------------------------------------------------"));

const sections = [
  "THIRD-PARTY NOTICES — Curbside AI web app",
  "Generated by web/scripts/third-party-notices.mjs. Data sources are credited on the Method page.",
  "",
  "=== Map data ===",
  "Basemap tiles: © OpenStreetMap contributors, available under the Open Database License (ODbL) 1.0,",
  "https://www.openstreetmap.org/copyright. Tiles extracted from a Protomaps daily build (an ODbL Produced Work),",
  "https://protomaps.com.",
  "",
  "=== Map style and sprites ===",
  "Protomaps basemap style and icon sprites, https://github.com/protomaps/basemaps — code BSD-3-Clause,",
  "map design CC0 1.0.",
  "",
  "=== Noto Sans (map label glyphs, served from /basemap/fonts) ===",
  "Copyright 2022 The Noto Project Authors (https://github.com/notofonts/latin-greek-cyrillic)",
  "This Font Software is licensed under the SIL Open Font License, Version 1.1.",
  "",
  oflBody.trim(),
  "",
  "=== Bundled software and web fonts ===",
];
for (const { id, license, text } of [...seen.values()].sort((a, b) => a.id.localeCompare(b.id))) {
  sections.push("", "-".repeat(72), `${id} — ${license}`, "-".repeat(72), text ?? "(no licence file in package; licence field above)");
}
mkdirSync(dirname(out), { recursive: true }); // public/ is absent in a fresh clone (its contents are generated)
writeFileSync(out, sections.join("\n") + "\n");
console.log(`third-party notices: ${seen.size} packages -> public/THIRD_PARTY_NOTICES.txt`);
